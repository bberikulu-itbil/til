#!/usr/bin/env python3
"""tokens.json + tokens-dark.json -> til/tokens.css. Run after any token change:
    python3 replica/design/build_css.py
"""
import json, pathlib

here = pathlib.Path(__file__).parent
light = json.loads((here / "tokens.json").read_text())
dark = json.loads((here / "tokens-dark.json").read_text())

def colors(t):
    return "".join(f"  --{k}: {v};\n" for k, v in t["color"].items())

rest = "".join(f"  --font-{k}: {v};\n" for k, v in light["font"].items())
rest += "".join(f"  --fs-{k}: {v['size']}px; --lh-{k}: {v['line']}px; --fw-{k}: {v['weight']};\n" for k, v in light["type"].items())
rest += "".join(f"  --space-{i}: {v}px;\n" for i, v in enumerate(light["space"]))
rest += "".join(f"  --radius-{k}: {v}px;\n" for k, v in light["radius"].items())
rest += "".join(f"  --shadow-{k}: {v};\n" for k, v in light["shadow"].items())
rest += "".join(f"  --{k if k == 'ease' else 'dur-' + k}: {v};\n" for k, v in light["motion"].items())
rest += "".join(f"  --{k.replace('_', '-')}: {v}px;\n" for k, v in light["layout"].items())

css = f"""/* Generated by replica/design/build_css.py from tokens.json and tokens-dark.json. Do not edit by hand. */
:root {{
{colors(light)}{rest}  color-scheme: light;
}}
@media (prefers-color-scheme: dark) {{
  :root:not([data-theme="light"]) {{
{colors(dark)}    color-scheme: dark;
  }}
}}
:root[data-theme="dark"] {{
{colors(dark)}  color-scheme: dark;
}}
"""
(here.parent.parent / "tokens.css").write_text(css)
print("wrote tokens.css")
